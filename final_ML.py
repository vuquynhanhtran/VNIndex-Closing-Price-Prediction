#Goal: build a working Decision tree regressor to use it as base for a Random
#Forest (multiple tree + bootstraping + averaging)
class DecisionTreeRegressor:
  def __init__(self, max_depth = 5, min_samples_split = 2): #store information to build the decision tree
    self.max_depth = max_depth #set the maximum depth for each tree
    self.min_samples_split = min_samples_split #min num of data point a node must have to be allowed to split - if fewer then it becomes a leaf
    self.root = None #placeholder that will eventually store the root node of my 🌳

  def fit(self, X, y):
    #this is NOT standardizing, we only standardize in linear regression
    #this is what kicks off the process. It calls the build_tree function on
    #the data and stores the resulting tree
    self.root = self._build_tree(X, y, depth = 0)

  def _build_tree(self,X,y,depth):#recursively build tree (yes/no split) until stopping conditions are met
    leaf_node = np.mean(y) #leaf prediction = mean of target values (y)
    # 1. Check stoppping conditions
    if depth >= self.max_depth: #if it reaches the max depth
      return leaf_node
    if len(y) < self.min_samples_split: #if the node has less than the said number of data points
      return leaf_node
    if self._mse(y) == 0: #all target values are the same
      return leaf_node

    best_feature, best_threshold = self._best_split(X, y) #get the best split
    if best_feature is None: #no feature + threshold combination found -> stop and make leaf
      return leaf_node
    # 3. Split the data into left and right
    left_mask = X[:, best_feature] <= best_threshold #'which rows go to the left child?' -> all samples where that feature value is <= threshold
    right_mask = X[:, best_feature] > best_threshold #'which rows go to the right child?' -> all samples where the feature's value is > threshold
    if np.sum(left_mask) == 0 or np.sum(right_mask) == 0: #this is for checking splits that leads to empty groups
      return leaf_node
    # 4. Recursively build left/right branches
    left_branch = self._build_tree(X[left_mask], y[left_mask], depth + 1) #take the data that went left (based on the mask) and build a subtree from it, also increase depth by 1 since i'm going one level deeper
    right_branch = self._build_tree(X[right_mask], y[right_mask], depth + 1) #take the data that went right (based on the mask) and build a subtree from it, alos increse depth by 1 since i'm going one level deeper
    # 5. Return node ductionary
    return {
    "feature": best_feature, #what feature it split on
    "threshold": best_threshold, #what threshold is used
    "left": left_branch, #what its left chilren are
    "right": right_branch} #what its right chilren are

  def _best_split(self,X,y): #compare the various thresholds and return the one with lowest MSE
    #Pseudocode
    # loop through every feature (column of X)
    # then loop through every unique value in that feature (potential threshold)
    # for each combo:
    #     it splits the target y into y_left and y_right based on the threshold
    #     calculates weighted mse after the split
    #     if that mse is better than the lowest so far -> store it
    # at the end return the best feature & threshold found.

    #1. Initialize variables
    best_feature = None
    best_threshold = None
    lowest_mse = float('inf')
    for feature_idx in range(X.shape[1]): #loop through features
      features_values = X[:, feature_idx] #get one column
      thresholds = np.unique(features_values) #get all unique values
      for threshold in thresholds:
        #split based on threshold
        left_mask = features_values < threshold
        right_mask = features_values >= threshold
        y_left = y[left_mask]
        y_right = y[right_mask]
        #if either split is empty, skip
        if len(y_left) == 0 or len(y_right) == 0:
          continue #continue can only be used within a loop
        mse_left = self._mse(y_left)
        mse_right = self._mse(y_right)
        weighted_mse = (len(y_left) * mse_left + len(y_right) * mse_right) / len(y)
        #then compare
        if weighted_mse < lowest_mse:
          best_feature = feature_idx
          best_threshold = threshold
          lowest_mse = weighted_mse
    return best_feature, best_threshold

  def _mse(self,y):#this is after _best_split since code order in a class doesn't matter functionally
    mse = sum((y - np.mean(y))**2) / len(y)
    return mse #use mean squared error since our dataset dont have that much outliers and target values usually follow a trend
    #mse is prefered since there is a large penalty for big errors, and its smoothness. This pushes models to learn stable, low variance predictions instead of jumping around to catch every little point

  def predict(self,X):
    #take the new data (X_test)
    #for each row, follow the tree down from root to leaf
    #return the predicted value (mean of target in that leaf)
    results = []
    for x in X:
      prediction = self._predict_row(x, self.root)
      results.append(prediction)
    return np.array(results)

  def _predict_row(self,x,node):
    #if the node is a float, its a leaf
    if not isinstance(node, dict):
      return node
    #other wise recurse down the tree
    #keep going down the tree until it hit a leaf
    #at a leaf, it returns the predicted value (like the mean of y's for that leaf)
    feature = node['feature'] #grab which column this node splits on
    threshold = node['threshold'] #get the threshold to compare against
    if x[feature] <= threshold:
      return self._predict_row(x, node['left']) #go down the left branch and call the function again
    else:
      return self._predict_row(x, node['right']) #go down the right branch and call the funcion again




class RandomForestRegressor:
  def __init__(self, n_trees, max_depth, min_samples_split): #store config
    self.n_trees = n_trees #numer of trees
    self.max_depth = max_depth #max_depth
    self.min_samples_split = min_samples_split #minimum number of values for splitting
    self.trees = [] #storing trees
    self.best_num_trees = 0 #this is early stopping logic: add tree one by one, we want to track when val_loss is lowest and remember how many trees there were
    #this is to track both training and validation loss
    self.train_losses = [] #list for tracking training loss across each tree added
    self.val_losses = [] #list for tracking validation loss across each tree added

  def fit(self, X, y, X_val=None, y_val=None, patience=100):
    self.trees = [] #storing number of trees with adding trees
    self.train_losses = [] #storing training loss across each adding trees
    self.val_losses = [] #storing validation loss across each adding trees

    best_val_loss = float('inf') #the threshold value of loss, naming it as an infitiny number since our goal is to minimize this
    best_num_trees = 0 #to track how many trees are there when the val_loss is lowest >>> to do early stopping
    wait = 0 #counter that increase every time val_loss doesn't improve
    for _ in range(self.n_trees):
        tree = DecisionTreeRegressor(
            max_depth=self.max_depth,
            min_samples_split=self.min_samples_split
        ) #get the tree from the decision tree regressor
        X_sample, y_sample = self._bootstrap_samples(X, y) #take a with-replacement sample aka bootstrap
        tree.fit(X_sample, y_sample) #'hey little tree, grow urself using this bootstrap sample of the data'
        self.trees.append(tree) #add the tree to the list of trees so we can count them later

        y_pred_train = self.predict(X)
        train_loss = np.mean((y - y_pred_train) ** 2)
        self.train_losses.append(train_loss)

        if X_val is not None and y_val is not None:
          y_pred_val = self.predict(X_val)
          val_loss = np.mean((y_val - y_pred_val) ** 2)
          self.val_losses.append(val_loss)
          if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_num_trees = len(self.trees)
            wait = 0
